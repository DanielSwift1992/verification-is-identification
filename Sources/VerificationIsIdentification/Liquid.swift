// Learning Is Liquid (Phase).
//
// Liquid names unresolved questions within a declared domain.
// A retained keyed record, an excluded candidate and a cheaper computation
// are distinct changes. Repeated certification can add none of them.
// A fixed sound candidate set shrinks under retaining observations.
// Finite completion additionally requires eventual separation of candidates
// that disagree on the question (Liquid LQ11).
//
// The observer, source, store and query mechanism belong to one whole.
// Local access can change under reversible whole dynamics. Closure alone
// supplies neither permanent memory nor a thermodynamic learning arrow.
//
// Pure types (§0′). These intersections expose declared coordinates.
// They do not encode an acquisition policy, an asymptotic convergence
// theorem, a physical phase transition or a Stefan equation.
// Liquid LQ12–LQ16 separately study the state of the medium: admitted
// forms, contact profiles, coordination and recovery of decomposition roles.
// Coupling, mobility and preserved properties need not vary together.
// Examples/Interactions supplies source-bound equality-contact exchanges,
// field recombination and recovery through complementary resident results.
// The rectangle obstruction determines when one crossed equality contact
// forces its complement. General role reconstruction is proved in LQ16.
// ReversedCutAgreement derives the restriction on a commutative cut result.
// LQ15 distinguishes joint union, profile intersection and partition laws.
// Its partial-evidence criterion refutes a greatest region from one refused
// joint set and its admitted contacts through a retained role, even after
// adding unknown internal roles. A positive boundary also needs coverage.
// Forgetting occurrence indices can give any downward-closed admission
// family from complete indexed sets. Its greatest compatibility region
// is a different question from the extent of one given occurrence.
// Matter M70 shows why an unrestricted internal record cannot select a local
// law: every finite table has a reversible prepared completion. Fixed capacity
// and repeated use supply restrictions that entropy alone does not specify.
// The protocols below still describe the older acquisition fragment.
// They do not encode those general theorems or classify physical phases.
