/// An accumulating-library declaration beside a monotone relation.
/// These coordinates do not specify the library update or its rate.
/// Infinite reach can have a finite generative description (B6–B8).
/// Resolved questions grow under fixed semantics and sound retaining
/// updates. Retention alone does not force a new distinction. [Liquid LQ1–2]
///
/// > Note: Table coverage, generative description and usable retrieval
/// > have different completion criteria. No claim that most domains
/// > remain permanently unresolved is encoded by this intersection.
///
public protocol LiquidPhase: KnowledgeAccumulates, Monotone {}

/// A monotone declaration with a structural distance and NoInverse axis.
/// A metric does not supply acquisition speed or a dendritic growth law.
/// The relative certificate bound counts distinct uncached answers.
/// New records can leave all remaining candidates intact. Completion
/// needs eventual separation of wrong-answer candidates. [Liquid LQ3–4, LQ11]
public protocol CrystallizationFront: LiquidPhase, DistanceOnStructures, NoInverse {}

/// An alignment measurement beside the liquid-phase declaration.
/// Positive aggregate correlation does not prove successful descent.
/// Query policy, loss basins and tie-breaking need separate premises.
/// Roughness statistics require a sampling measure and nonzero variance.
/// Laminar and turbulent are proposed analogies, without a derived
/// Reynolds number or fluid equation. [Liquid LQ5–6, Gradient GA6]
public protocol SearchFlow: LiquidPhase, AlignmentCoefficient {}

/// The search and frontier declarations share this intersection.
/// A feedback implementation must connect proposals, scoped checking,
/// retaining storage and a later policy. No update or cost improvement
/// follows from the intersection. The historical Stefan name carries
/// an analogy, not an interface equation or a strict arrow. [Liquid LQ8–9]
public protocol StefanCoupling: CrystallizationFront, SearchFlow {}

/// A scoped PASS-to-membership relation beside the search/front axes.
/// A learned generator can propose proofs for a formal checker.
/// Certification concerns the encoded claim under its premises.
/// It does not establish representability of an unknown actual law.
/// The store and query policy have separate retention and progress
/// obligations. An unresolved question can trigger another query,
/// a set of compatible answers or abstention. [Liquid LQ10]
///
/// > Note: Neural proposal and formal verification are compatible.
/// > This declaration supplies no impossibility result for statistical
/// > AI and no requirement that each success creates a new record.
public protocol GateIsMembrane: StefanCoupling, PassImpliesMembership {}
